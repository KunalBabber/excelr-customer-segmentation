"""ExcelR Customer Segmentation | Streamlit dashboard using notebook-exported PKL.

Run the Jupyter notebook first to generate customer_segmentation.pkl.
This dashboard reads saved results and DOES NOT retrain models.
Only load a PKL generated by your own trusted notebook.
"""
from pathlib import Path
import pickle
import numpy as np
import pandas as pd
import plotly.express as px
import streamlit as st

st.set_page_config(page_title="ExcelR | Customer Segmentation", page_icon="📊", layout="wide")
st.title("Customer Segmentation | ExcelR")
st.caption("Five clustering models • Model evaluation • Customer profiles • PCA")

# STEP 1: Load the results exported by the notebook.
# Caching avoids loading the same file on every widget interaction.
@st.cache_resource
def load_results():
    path = Path(__file__).resolve().parent / "customer_segmentation.pkl"
    if not path.exists():
        raise FileNotFoundError("customer_segmentation.pkl not found. Run the notebook export cell first.")
    with path.open("rb") as file:
        return pickle.load(file)  # Load only your own trusted PKL file.

try:
    saved = load_results()
    df = saved["customers"].copy()
    features = saved["feature_names"]
    labels = saved["labels"]
    scores = saved["evaluation"].copy()
    coords = np.asarray(saved["pca_coordinates"])
    if len(coords) != len(df) or any(len(v) != len(df) for v in labels.values()):
        raise ValueError("Saved labels/PCA data do not match the customer count.")
except Exception as exc:
    st.error(f"Unable to load saved notebook results: {exc}")
    st.stop()

# STEP 2: Create tabs for the presentation.
overview, models_tab, evaluation_tab, segments_tab, download_tab = st.tabs([
    "Dataset overview", "Five models", "Model evaluation", "Customer segments & PCA", "Download"
])

with overview:
    # The notebook's selected feature columns were standardized in place.
    # Therefore, those columns are in scaled units, not original currency/age units.
    a, b, c = st.columns(3)
    a.metric("Customers", f"{len(df):,}")
    b.metric("Columns", len(df.columns))
    c.metric("Clustering features", len(features))
    st.dataframe(df.head(20), use_container_width=True)
    st.info("Notebook preprocessing standardized the 13 clustering features in place. Their saved values are scaled (z-score) values, not original units.")
    feature = st.selectbox("Feature distribution", features)
    st.plotly_chart(px.histogram(df, x=feature, nbins=35, title=f"Distribution: {feature}"), use_container_width=True)

with models_tab:
    # Show cluster sizes produced by each trained model.
    st.write("All five models were trained in the Jupyter notebook using the same feature matrix.")
    for name, predicted in labels.items():
        with st.expander(name, expanded=(name == "K-Means")):
            counts = pd.Series(predicted).value_counts().sort_index().rename_axis("Cluster").reset_index(name="Customers")
            counts["Cluster"] = counts["Cluster"].astype(str)
            st.dataframe(counts, use_container_width=True)
            st.plotly_chart(px.bar(counts, x="Cluster", y="Customers", title=f"{name} — Cluster sizes"), use_container_width=True)
            if name == "DBSCAN":
                st.caption("Cluster -1 represents noise points, not a regular customer segment.")

with evaluation_tab:
    # Higher Silhouette/Calinski-Harabasz and lower Davies-Bouldin are generally preferred.
    st.dataframe(scores.round(4), use_container_width=True)
    for metric in ["Silhouette Score", "Davies-Bouldin Index", "Calinski-Harabasz Index"]:
        st.plotly_chart(px.bar(scores, x="Model", y=metric, title=metric), use_container_width=True)
    st.caption("DBSCAN noise was excluded from its evaluation metrics in the notebook. Undefined scores appear blank.")
    valid = scores.dropna(subset=["Silhouette Score"])
    if not valid.empty:
        best = valid.loc[valid["Silhouette Score"].idxmax()]
        st.success(f"Highest Silhouette Score: {best['Model']} ({best['Silhouette Score']:.4f}). Compare other metrics and business relevance too.")

with segments_tab:
    # Select a model and profile the saved cluster assignments.
    selected = st.selectbox("Choose clustering model", list(labels))
    result = df.copy()
    result["Cluster"] = labels[selected]
    st.subheader("Average feature values by cluster (standardized units)")
    st.dataframe(result.groupby("Cluster")[features].mean().round(3), use_container_width=True)
    st.caption("These profiles use standardized feature values, not original income or spending amounts.")
    st.subheader("PCA projection (2 dimensions)")
    chart = pd.DataFrame({"PC1": coords[:, 0], "PC2": coords[:, 1], "Cluster": pd.Series(labels[selected]).astype(str)})
    st.plotly_chart(px.scatter(chart, x="PC1", y="PC2", color="Cluster", opacity=0.65, title=f"PCA — {selected}"), use_container_width=True)
    st.caption("PCA is for visualization only; the notebook trained its models on all 13 features.")

with download_tab:
    # Export all saved cluster assignments and evaluation metrics.
    output = df.copy()
    for name, predicted in labels.items():
        output["Cluster_" + name.replace(" ", "_")] = predicted
    st.download_button("Download customer segments CSV", output.to_csv(index=False).encode("utf-8"), "customer_segments.csv", "text/csv")
    st.download_button("Download model evaluation CSV", scores.to_csv(index=False).encode("utf-8"), "model_evaluation.csv", "text/csv")
    st.info("Deployment: Upload app.py, customer_segmentation.pkl, and requirements.txt to GitHub, then deploy app.py on Streamlit Community Cloud.")
